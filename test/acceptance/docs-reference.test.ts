import { spawnSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { REPO_ROOT } from './helpers.js';

const SCRIPT = path.join(REPO_ROOT, 'scripts/docs-reference.mjs');
const GENERATED = path.join(REPO_ROOT, 'docs/reference/_generated');

describe('the generated CLI and configuration reference', () => {
  it('matches the built CLI and schemas/config.json', () => {
    const result = spawnSync(process.execPath, [SCRIPT, '--check'], { cwd: REPO_ROOT, encoding: 'utf8' });
    expect(result.status, `${result.stdout}${result.stderr}`).toBe(0);
  });

  it('says that it is generated and must not be edited', () => {
    for (const name of ['cli.md', 'configuration.md']) {
      const content = readFileSync(path.join(GENERATED, name), 'utf8');
      expect(content.startsWith('<!-- Generated by `node scripts/docs-reference.mjs`'), name).toBe(true);
      expect(content.split('\n')[0], name).toMatch(/Do not edit/);
    }
  });

  it('is included by the English and Japanese reference pages', () => {
    for (const [page, include] of [
      ['docs/reference/cli.md', '<!--@include: ./_generated/cli.md-->'],
      ['docs/reference/configuration.md', '<!--@include: ./_generated/configuration.md-->'],
      ['docs/ja/reference/cli.md', '<!--@include: ../../reference/_generated/cli.md-->'],
      ['docs/ja/reference/configuration.md', '<!--@include: ../../reference/_generated/configuration.md-->'],
    ] as const)
      expect(readFileSync(path.join(REPO_ROOT, page), 'utf8'), page).toContain(include);
  });
});
